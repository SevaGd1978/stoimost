export const REGION_NAMES = REGIONS.map(([name]) => name).sort((a, b) => a.localeCompare(b, 'ru'));

export function regionFromText(text) {
  const s = String(text ?? '').replace(/ё/gi, 'е').replace(/\s+/g, ' ');
  if (!s.trim()) return null;
  // В адресе субъект идёт раньше района и города: «Ростовская обл, г Донецк» — это Ростовская область.
  let best = null;
  for (const [name, re] of REGIONS) {
    const m = re.exec(s);
    if (m && (!best || m.index < best.index || (m.index === best.index && m[0].length > best.length))) {
      best = { name, index: m.index, length: m[0].length };
    }
  }
  return best?.name ?? null;
}
